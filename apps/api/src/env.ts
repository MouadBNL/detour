/**
 * Parses the Worker's bindings (`secrets.required` in wrangler.jsonc: `wrangler secret put` in
 * production, `.dev.vars` in `wrangler dev`) into a typed `Env`. The only place in apps/api that reads configuration (enforced by lint): everything
 * else receives the parsed `Env` (or what `worker.ts` builds from it) as an argument.
 */
import { err, ok, type Result } from "@detour/result";
import * as z from "zod";

const EnvSchema = z.object({
  /** WorkOS API key (`sk_test_...` / `sk_live_...`). A secret in production. */
  WORKOS_API_KEY: z.string().min(1).default("sk_test_dev_placeholder"),
  /** WorkOS Client ID (`client_...`). */
  WORKOS_CLIENT_ID: z.string().min(1).default("client_dev_placeholder"),
  /**
   * 32+ char password that encrypts the sealed session cookie. A secret, with no default: a
   * committed value would let anyone forge sessions. Unset (dev without .dev.vars), `worker.ts`
   * uses a random one per isolate, so sessions last until `wrangler dev` restarts.
   */
  WORKOS_COOKIE_PASSWORD: z.string().min(32).optional(),
  /** Public callback URL registered in WorkOS AuthKit (web proxy origin in dev). */
  WORKOS_REDIRECT_URI: z
    .url({ protocol: /^https?$/ })
    .default("http://localhost:5173/api/auth/callback"),
});

export type Env = z.infer<typeof EnvSchema>;

type InvalidEnv = { readonly type: "invalid_env"; readonly issues: string };

/** `source` is the Worker's `Bindings` (generated by `wrangler types`), or a plain object in tests. */
export function loadEnv(source: Partial<Record<keyof Env, unknown>>): Result<Env, InvalidEnv> {
  const parsed = EnvSchema.safeParse(source);
  if (!parsed.success) return err({ type: "invalid_env", issues: z.prettifyError(parsed.error) });
  return ok(parsed.data);
}
